function syf_seed_articles() {
    $version = defined('SYF_THEME_VERSION') ? SYF_THEME_VERSION : '0.4.3';
    if (get_option('syf_articles_seed_version') === $version) return;
    foreach (syf_article_library() as $slug=>$article) {
        $existing = get_page_by_path($slug, OBJECT, 'post');
        $postarr = array(
            'post_title'=>$article['title'],
            'post_name'=>$slug,
            'post_content'=>$article['content'],
            'post_excerpt'=>$article['excerpt'],
            'post_status'=>'publish',
            'post_type'=>'post',
        );
        if ($existing) {
            if (!get_post_meta($existing->ID, '_syf_seeded_article', true)) continue;
            $postarr['ID']=$existing->ID;
            $post_id=wp_update_post($postarr,true);
        } else {
            $post_id=wp_insert_post($postarr,true);
        }
        if (is_wp_error($post_id) || !$post_id) continue;
        update_post_meta($post_id,'_syf_seeded_article',1);
        update_post_meta($post_id,'_syf_article_category',$article['category']);
        update_post_meta($post_id,'_syf_article_cover',$article['cover']);
        $term=term_exists($article['category'],'category');
        if (!$term) $term=wp_insert_term($article['category'],'category');
        if (!is_wp_error($term)) {
            $term_id=is_array($term)?(int)$term['term_id']:(int)$term;
            wp_set_post_categories($post_id,array($term_id),false);
        }
    }
    update_option('syf_articles_seed_version',$version);
}
add_action('init','syf_seed_articles',35);

function syf_article_cover_url($post_id) {
    $cover=get_post_meta($post_id,'_syf_article_cover',true);
    if (!$cover) $cover='project-01.jpg';
    return get_template_directory_uri().'/assets/images/react/'.rawurlencode($cover);
}
function syf_article_reading_time($post_id) {
    $content=wp_strip_all_tags(get_post_field('post_content',$post_id));
    $words=preg_split('/\s+/u',trim($content));
    $count=is_array($words)?count(array_filter($words)):0;
    return max(4,(int)ceil($count/170));
}
